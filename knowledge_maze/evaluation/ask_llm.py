from typing import List, Dict
from collections import Counter

from knowledge_maze.tools.api_tools import *

# Initialize LLM prompts:
ASK_QUESTION_PROMPT = """"""
LLM_JUDGE_PROMPT = """You are a strict evaluator. Given a question and two possible answers (Option A and Option B), 
                      compare a reference answer to them. Return only `True` if the reference answer best matches 
                      Option A, and `False` otherwise. Respond only with `True` or `False`."""

# Create LLM API call objects:
qa_model = gptAPI(ASK_QUESTION_PROMPT,
                  output_format='list',
                  temperature = 1.5,
                  max_concurrent_requests = 100,
                  max_rpm=4900)
judge_model = gptAPI(LLM_JUDGE_PROMPT,
                     output_format='list',
                     temperature = 0.2,
                     max_concurrent_requests = 100,
                     max_rpm=4900)


async def judge_answer(answers: List[str], options: Dict[str, str]) -> Dict[str, float]:
    """
    Asynchronously uses the judge_model to classify a list of unstructured
    answers against a dictionary of valid options and calculates the probability
    distribution for each option's key.

    Note: This is an async function and must be called with 'await'.

    Args:
        answers (List[str]): A list of potentially unstructured answers from a model.
        options (Dict[str, str]): A dictionary where keys are descriptive labels
                                  (e.g., 'Memory answer') and values are the
                                  canonical answers (e.g., 'Motown').

    Returns:
        Dict[str, float]: A dictionary with the same keys as the input `options`
                          dictionary, where each value is the calculated probability.
    """
    if not answers:
        return {key: 0.0 for key in options.keys()}

    # Extract the canonical answer values for the judge prompt.
    option_values = list(options.values())

    # Create a list of prompts for the judge_model to normalize each answer.
    prompts = []
    for answer in answers:
        prompt = f"""
        You are an impartial judge. Your task is to determine which of the following options an answer corresponds to.

        Valid Options:
        {option_values}

        Answer to Judge:
        "{answer}"

        Which option does the answer correspond to? Respond with ONLY the text of the matching option from the list. 
        If the answer does not correspond to any of the options, respond with the single word 'Invalid'.
        """
        prompts.append(prompt)

    # Get the model's judgment for each answer.
    judged_responses = await judge_model.async_run(prompts)

    # Flatten the response and clean up the results.
    normalized_answers = [result[0].strip() for result in judged_responses if result]

    # If all responses were empty, return all options with 0 probability.
    if not normalized_answers:
        return {key: 0.0 for key in options.keys()}

    # Create a reverse map from canonical value back to the descriptive key.
    value_to_key_map = {value: key for key, value in options.items()}

    # Initialize the result dictionary with all original keys set to 0.0.
    result_probabilities = {key: 0.0 for key in options.keys()}

    # Count the occurrences of each normalized answer.
    total_count = len(normalized_answers)
    answer_counts = Counter(normalized_answers)

    # Calculate probability for each counted answer and map it to the original key.
    for value, count in answer_counts.items():
        key = value_to_key_map.get(value)  # Get the original key (e.g., 'Memory answer')
        if key:
            result_probabilities[key] = count / total_count
        else:
            # Handle 'Invalid' or other unexpected outputs from the judge model.
            result_probabilities[value] = count / total_count

    return result_probabilities


async def ask_llm(question: str, context: str, answer: str, num_retries: int) -> List[str]:
    """
    Uses the qa_model to ask the same question multiple times in parallel to
    generate a variety of answers.

    Args:
        question (str): The question to be answered.
        context (str): The context to use for answering the question.
        answer (str): The answer to the question.
        num_retries (int): The number of times to ask the question.

    Returns:
        List[str]: A list of all answers generated by the model.
    """
    prompt = f"""
    You are a logical reasoner. Your task is to answer the question using only the information found in the context below.
    \n\n
    Rules:\n
    - Do NOT use any external or real-world knowledge.\n
    - Only rely on statements explicitly made in the context, even if they are factually incorrect.\n
    - If the context contains contradictions, choose the answer that is best supported by the majority of consistent clues.\n
    - Your answer must be a single entity or phrase clearly supported by the context.\n\n

    Context:\n
    {context}\n\n

    Question:\n
    {question}\n\n
    
    Important note:
    The answer is *not* {answer}
    """
    # Create a list of identical prompts for batch processing.
    prompts = [prompt] * num_retries

    # qa_model's output_format is 'list', so async_run returns a list of lists,
    # e.g., [['answer 1'], ['answer 2'], ['answer 1']].
    nested_answers = await qa_model.async_run(prompts)

    # Flatten the list of lists into a single list of answer strings.
    # We take the first element [0] from each sublist and handle potential empty responses.
    answers = [result[0] for result in nested_answers if result]

    return answers


