"""
CoT Knowledge Conflict Evaluation Module
========================================

This module provides the `CoTKnowledgeConflictJudge` class, a specialized
evaluation tool designed to categorize and audit Large Language Model (LLM)
Chain-of-Thought (CoT) responses in the presence of conflicting information.

The judge operates as a meta-evaluator, utilizing a highly-curated system
prompt to extract structured insights from model reasoning. It specifically
targets the tension between internal parametric knowledge ('Memory') and
external contextual inputs ('Claim' and 'Evidence').

Key Evaluation Dimensions:
--------------------------
1. **Source Classification**: Identifies which specific source the model
   prioritized for its final answer. Categorizations include 'memory', 'claim',
   'evidence', 'both' (synthesis), 'abstain' (refusal/hedging), or 'other'.
2. **Conflict Awareness**: A boolean audit of whether the model's reasoning
   explicitly acknowledged the existence of competing values or source
   ambiguity within the provided context.
3. **Qualitative Explanation**: Captures a brief natural language
   justification for the assigned labels to assist in downstream error analysis.

Technical Implementation:
-------------------------
* **LLM-as-a-Judge**: Leverages the `google/gemini-3.1-flash-lite-preview`
  model via the OpenRouter API for high-speed, cost-effective evaluation.
* **Robust JSON Sanitization**: Includes a comprehensive validation layer
  (`_validate_output`) to handle common LLM output issues such as markdown
  code blocks, inconsistent casing, and malformed JSON structures.
* **Concurrency Support**: Built on an asynchronous architecture to allow
  efficient batch evaluation of large datasets.

Note:
-----
The classification is strictly derived from the model's final explicit
conclusion. Reasoning steps are used solely to determine the
'conflict_acknowledged' flag.
"""

import os
import json
import yaml
import random
from dotenv.main import load_dotenv
from typing import List, Dict, Optional

from knowledge_maze.tools.api_tools import OpenRouterAPI

load_dotenv()
REPO_PATH = os.getenv('REPO_PATH')

# The strict list of acceptable outputs
VALID_CATEGORIES = [
    'memory',
    'claim',
    'evidence',
    'abstain',
    'other'
]


class CoTKnowledgeConflictJudge:
    """
    An evaluation module that categorizes LLM Chain-of-Thought (CoT) answers.
    Evaluates both the final decision and the model's awareness of conflicting context.
    """

    def __init__(self, model_name: str, max_concurrent_requests: int = 20, max_rpm: int = 250):
        # The System Prompt is engineered to extract two structured variables
        system_prompt = """You are a formal evaluation judge for a natural language processing experiment on knowledge conflicts. 
You will be provided with:
1. Question: The specific query the model was asked to answer.
2. Context: Three information sources (Memory, Claim, Evidence).
3. Model Response: The reasoning steps and the final answer generated by the model.

Your task is to evaluate the response and extract two specific data points:


### 1. CLASSIFICATION (string)
Determine which source the model's FINAL conclusion prioritizes or whether it fails to commit to a single source.
- memory: The final answer matches the 'Memory' value.
- claim: The final answer matches the 'Claim' value.
- evidence: The final answer matches the 'Evidence' value.
- abstain: The model fails to commit to a single final value, either through explicit refusal, synthesis of multiple conflicting values (e.g., "both A and B"), or hedging without a definitive conclusion.
- other: The model provides a coherent final answer that does not match Memory, Claim, or Evidence, and is not a synthesis or abstention (i.e., an alternative external or hallucinated value, or misaligned but decisive response).

The CLASSIFICATION must be determined ONLY from the final explicit answer statement.
Do NOT infer final decision from reasoning, comparisons, or explanations.
If multiple candidate values are discussed without a clear final selection, classify as “abstain”.
Only assign a source label (memory / claim / evidence) if a single value is explicitly presented as the final answer (e.g., “Final answer: X”, “The answer is X”).


### 2. DUAL-TARGET AWARENESS (boolean)

Determine whether the model explicitly acknowledges BOTH competing answers provided in the input:
- Claim answer (direct/asserted answer)
- Evidence answer (derived/calculated answer)

Mark TRUE only if the response explicitly recognizes the Claim and Evidence answers as different competing interpretations or conclusions.

This requires:
1. The Claim answer is referenced as a stated, asserted, or directly provided result.
2. The Evidence answer is derived, computed, or identified through reasoning over the context.

Examples of TRUE:
- "The text states X, but calculating from the data gives Y."
- "One source suggests A, while the evidence supports B."

Mark FALSE if:
- Only one target is explicitly acknowledged.
- Targets are mentioned only as ordinary items during counting, ranking, filtering, comparison, elimination, or candidate evaluation.
- Multiple entities or values are discussed without framing Claim and Evidence as conflicting or alternative conclusions.

[CRITICAL]
Mentioning Claim, Evidence, or Memory answers during normal problem solving does NOT imply awareness.

TRUE requires explicit recognition that the Claim and Evidence answers correspond to different conflicting conclusions.


### 3. EXPLANATION (string)
Brief justification (1–3 sentences) explaining why you assigned the classification and conflict flag.
This is for analysis only and must not affect downstream metric computation.

### OUTPUT FORMAT (STRICT)
Return ONLY a valid JSON object with exactly three keys:

{
  "classification": string,
  "dual_awareness": boolean,
  "explanation": string
}
"""

        # Instantiate the API using the model extracted directly from the config file
        self.api = OpenRouterAPI(
            system_prompt=system_prompt,
            model=model_name,
            output_format=None,  # Relies on prompt engineering for JSON
            temperature=0.0,
            max_tokens=100,
            max_concurrent_requests=max_concurrent_requests,
            max_rpm=max_rpm,
            return_thinking=False
        )

    def _validate_output(self, raw_output: str) -> Optional[dict]:
        """Sanitizes the model output to ensure it returns a valid dict schema."""
        if not raw_output:
            return None

        cleaned = raw_output.strip()
        if cleaned.startswith("```json"):
            cleaned = cleaned.replace("```json", "", 1)
        if cleaned.endswith("```"):
            cleaned = cleaned[::-1].replace("```"[::-1], "", 1)[::-1]
        cleaned = cleaned.strip()

        try:
            parsed = json.loads(cleaned)

            # 1. Validate Classification
            raw_class = str(parsed.get("classification", "other")).strip().lower()
            final_class = "other"

            if raw_class in VALID_CATEGORIES:
                final_class = raw_class
            else:
                for category in VALID_CATEGORIES:
                    if category in raw_class:
                        final_class = category
                        break

            # 2. Validate Boolean
            raw_aware = parsed.get("dual_awareness", False)
            if isinstance(raw_aware, str):
                final_aware = raw_aware.lower() == 'true'
            else:
                final_aware = bool(raw_aware)

            # 3. Validate Explanation
            raw_expl = parsed.get("explanation", "")
            explanation = str(raw_expl) if raw_expl is not None else ""

            return {
                "classification": final_class,
                "dual_awareness": final_aware,
                "explanation": explanation
            }

        except json.JSONDecodeError:
            return None

    async def evaluate_batch(self, dataset: list, desc: str = "Evaluating CoT Answers") -> list:
        """Evaluates a batch of samples concurrently."""
        prompts = []
        for sample in dataset:
            context = sample.get('context', {})
            response = sample.get('model_response', '')
            question = sample.get('question', '')

            p = f"""Question: {question}
Context:
- Memory: {context.get('Memory', 'N/A')}
- Claim: {context.get('Claim', 'N/A')}
- Evidence: {context.get('Evidence', 'N/A')}

Model CoT Response:
"{response}"
"""
            prompts.append(p)

        raw_results = await self.api.async_run(prompts, desc=desc)
        return [self._validate_output(res) for res in raw_results]


class KnowledgeMazeIncrementalJudge:
    def __init__(self, config_path: str, experiment_type: str):
        """
        Args:
            config_path: Path to the centralized YAML config file.
            experiment_type: One of 'baseline', 'cot', 'scaling', or 'hedged'.
        """
        self.experiment_type = experiment_type.lower()
        repo_path = REPO_PATH

        # 1. Load configuration
        with open(config_path, 'r', encoding='utf-8') as f:
            self.config = yaml.safe_load(f)

        # 2. Extract configuration contexts
        self.params = self.config.get('parameters', {})
        judge_model = self.config.get('models', {}).get('judge_model', 'google/gemini-3.1-flash-lite-preview')

        # 3. Resolve the target directory where the raw model output files sit
        results_rel_path = self.config.get('results_folder', {}).get(self.experiment_type)
        if not results_rel_path:
            raise KeyError(f"Results folder lookup failed for experiment type: '{self.experiment_type}'")

        self.results_dir = os.path.join(repo_path, results_rel_path)

        # 4. Spin up the inner evaluation judge with config parameters
        self.judge = CoTKnowledgeConflictJudge(
            model_name=judge_model,
            max_concurrent_requests=self.params.get('max_concurrent', 20),
            max_rpm=400
        )

    def _get_model_files(self) -> List[str]:
        """Returns all model result JSON files in the resolved target experiment directory."""
        if not os.path.exists(self.results_dir):
            print(f"⚠️ Warning: Target directory does not exist: {self.results_dir}")
            return []
        return [f for f in os.listdir(self.results_dir) if f.endswith(".json")]

    async def run_judge_incremental(self, sample_limit: Optional[int] = None):
        """Processes model files incrementally, only evaluating iterations lacking judge verdicts."""
        model_files = self._get_model_files()

        for filename in model_files:
            file_path = os.path.join(self.results_dir, filename)
            print(f"\n⚖️ Judging model output folder: {self.experiment_type.upper()} | File: {filename}")

            with open(file_path, 'r', encoding='utf-8') as f:
                data = json.load(f)

            # 1. Isolate pending keys where iterations lack a 'judge_results' field
            pending_sample_ids = []
            for s_id, sample in data.items():
                if any('judge_results' not in iter for iter in sample.get('responses', [])):
                    pending_sample_ids.append(s_id)

            if not pending_sample_ids:
                print(f"--- All existing iterations inside {filename} are fully judged. Skipping.")
                continue

            # 2. Handle optional chunk limits via random subset slicing
            if sample_limit and sample_limit < len(pending_sample_ids):
                selected_ids = random.sample(pending_sample_ids, sample_limit)
                print(
                    f"--- Checkpoint limit hit. Slicing {sample_limit} samples out of {len(pending_sample_ids)} pending entries.")
            else:
                selected_ids = pending_sample_ids
                print(f"--- Processing all {len(pending_sample_ids)} pending entries.")

            # 3. Assemble tasks flattening iterations for batch processing
            pending_tasks = []
            for s_id in selected_ids:
                sample = data[s_id]
                gt = sample.get('gt_answers', {})
                context = {
                    'Memory': gt.get('Memory'),
                    'Claim': gt.get('Claim'),
                    'Evidence': gt.get('Evidence')
                }

                for idx, iteration in enumerate(sample.get('responses', [])):
                    if 'judge_results' not in iteration:
                        pending_tasks.append({
                            's_id': s_id,
                            'idx': idx,
                            'payload': {
                                'question': sample.get('question'),
                                'model_response': iteration.get('raw_response'),
                                'context': context
                            }
                        })

            # 4. Batch Dispatch and Evaluation Pipeline Sync
            if pending_tasks:
                batch_payloads = [t['payload'] for t in pending_tasks]
                results = await self.judge.evaluate_batch(batch_payloads, desc=f"Evaluating: {filename}")

                for task, verdict in zip(pending_tasks, results):
                    if verdict:
                        s_id = task['s_id']
                        idx = task['idx']
                        data[s_id]['responses'][idx]['judge_results'] = verdict

                self._save_results(file_path, data)
                print(f"✅ State updated and committed for {filename}.")

    def _save_results(self, path: str, data: Dict):
        temp_path = path + ".tmp"
        with open(temp_path, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=4)
        os.replace(temp_path, path)