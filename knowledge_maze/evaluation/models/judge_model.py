from knowledge_maze.tools.api_tools import OpenRouterAPI

# The strict list of acceptable outputs
VALID_CATEGORIES = [
    'memory',
    'claim',
    'evidence',
    'both',
    'no answer',
    'other answer',
    'other'
]


class KnowledgeConflictJudge:
    """
    An evaluation module that categorizes LLM answers based on conflicting context sources.
    Wraps the OpenRouterAPI class for asynchronous batch processing.
    """

    def __init__(self, max_concurrent_requests: int = 20, max_rpm: int = 1000):
        # The System Prompt is engineered as a strict classification gate
        system_prompt = """You are a formal evaluation judge for a natural language processing experiment on knowledge conflicts. 
You will be provided with:
1. Question: The specific query the model was asked to answer.
2. Context: Three information sources (Memory, Claim, Evidence).
3. Answer: The response generated by the model under evaluation.

Your task is to determine which source the Answer prioritizes in direct relation to the Question.

### CATEGORIES:
- memory: The answer matches the 'Memory' value.
- claim: The answer matches the 'Claim' value.
- evidence: The answer matches the 'Evidence' value.
- both: The answer explicitly mentions or synthesizes multiple conflicting values (e.g., "The table says X but the text says Y").
- no answer: The model explicitly refuses to answer, states it does not know, or provides a hedge with no value.
- other answer: The model provides a coherent, relevant value that does not match Memory, Claim, or Evidence.
- other: The response is nonsensical, contains only meta-talk, or is a formatting error.

### CRITICAL INSTRUCTION:
Compare the Answer's core value to the values provided in the Context for that specific Question. 
Output ONLY the exact category name in lowercase. Do not include punctuation, bolding, or markdown."""

        # Instantiate the API with Flash-Lite and strict parameters
        self.api = OpenRouterAPI(
            system_prompt=system_prompt,
            model="google/gemini-3.1-flash-lite-preview",
            output_format=None,  # Raw string output
            temperature=0.0,  # Zero variance for consistent classification
            max_tokens=10,  # Constrain generation to just the category name
            max_concurrent_requests=max_concurrent_requests,
            max_rpm=max_rpm,
            return_thinking=False
        )

    def _validate_output(self, raw_output: str) -> str:
        """Sanitizes the model output to ensure it matches the VALID_CATEGORIES list."""
        if not raw_output:
            return "other"

        # Clean the string of accidental markdown, punctuation, or whitespace
        cleaned = raw_output.strip().lower().replace(".", "").replace('"', '').replace("'", "").replace("`", "")

        # 1. Direct Match
        if cleaned in VALID_CATEGORIES:
            return cleaned

        # 2. Substring Match (Heuristic fallback if the model gets chatty)
        # e.g., if the model outputs "The category is: evidence"
        for category in VALID_CATEGORIES:
            # Check longer strings first so 'other answer' is checked before 'answer' (if 'answer' were a category)
            if category in cleaned:
                return category

        # 3. Default Fallback
        return "other"

    async def evaluate_single(self, question: str, answer: str, context: dict) -> str:
        """Evaluates a single sample."""
        user_prompt = f"""Question: {question}

Context:
- Memory: {context.get('Memory', 'N/A')}
- Claim: {context.get('Claim', 'N/A')}
- Evidence: {context.get('Evidence', 'N/A')}

Answer to classify:
"{answer}"
"""
        raw_result = await self.api.get_response(user_prompt)
        return self._validate_output(raw_result)

    async def evaluate_batch(self, dataset: list, desc: str = "Evaluating Answers") -> list:
        """
        Evaluates a batch of samples concurrently.
        Expected dataset format: [{'answer': '...', 'context': {'Memory': '...', 'Claim': '...', 'Evidence': '...'}}]
        """
        prompts = []
        for sample in dataset:
            context = sample.get('context', {})
            answer = sample.get('answer', '')
            question = sample.get('question', '')

            p = f"""Question: {question}
Context:
- Memory: {context.get('Memory', 'N/A')}
- Claim: {context.get('Claim', 'N/A')}
- Evidence: {context.get('Evidence', 'N/A')}

Answer to classify:
"{answer}"
"""
            prompts.append(p)

        # Run through the OpenRouter async queue
        raw_results = await self.api.async_run(prompts, desc=desc)

        # Validate and return the mapped list
        return [self._validate_output(res) for res in raw_results]
