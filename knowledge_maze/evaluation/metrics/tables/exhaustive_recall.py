"""
Exhaustive Answer Retrieval and Recall Evaluation Engine.

This module provides deterministic verification pipelines to measure the information
extraction capacity of Large Language Models (LLMs). Specifically, it assesses
an extraction model's ability to exhaustively retrieve dual ground-truth targets
(both the underlying authoritative 'Claim' and the factual 'Evidence') from a given
evaluation context without dropping critical sub-components.

The evaluation engine supports polymorphic structural matching across three distinct
ground-truth data topologies:
1. Numeric Tolerances: Employs floating-point proximity matching via absolute difference checks.
2. Unordered Sets / Bags of Items: Partitions multi-item comma-separated or enumerated target
   strings, applying fuzzy alignment thresholds across generated strings.
3. Strict Substring Entities: Executes robust partial-ratio matching thresholds via `rapidfuzz`.

Formally, for a dataset of size $N$, the module tabulates independent recall markers
alongside a strict joint-intersection performance metric:
    $$\text{Joint Recall} = \frac{1}{N} \sum_{i=1}^{N} \mathbb{I}(\text{Claim}_i \in \hat{Y}_i \land \text{Evidence}_i \in \hat{Y}_i)$$
Where $\hat{Y}_i$ represents the flattened set of parsed model extractions.

Core Components
---------------
* ExhaustiveRecallEvaluator: Primary class orchestrating JSON extraction, predictive array
  flattening, structural ground-truth identification, and sample-level metric injection.
* run_recall_analysis: High-level runner function that handles multi-model file evaluation
  concurrency, aggregates final pandas dataframes, and displays styled performance reports.
"""

import os
import re
import json
import pandas as pd
from copy import deepcopy
from rapidfuzz import fuzz
from dotenv import load_dotenv
from IPython.display import display

from knowledge_maze.tools.utils import load_json

load_dotenv()
REPO_PATH = os.getenv('REPO_PATH')


class ExhaustiveRecallEvaluator:
    """
    Deterministic evaluator for exhaustive answer retrieval.

    Adds to each sample:
    - got_claim
    - got_evidence
    - verdict

    Verdict == True iff both claim and evidence were retrieved.
    """

    def __init__(
        self,
        fuzzy_threshold_entity=90,
        fuzzy_threshold_list=85
    ):
        self.fuzzy_threshold_entity = fuzzy_threshold_entity
        self.fuzzy_threshold_list = fuzzy_threshold_list

    def extract_answers(self, raw_response):
        try:
            data = json.loads(raw_response)
            res = data.get("answers") or data.get("final_answers") or []
            return res if isinstance(res, list) else [res]
        except Exception:
            pass

        # Regex array target extraction fallback
        try:
            match = re.search(r'"(?:answers|final_answers)"\s*:\s*(\[[\s\S]*?\])', raw_response)
            if match:
                arr = json.loads(match.group(1))
                return arr if isinstance(arr, list) else [arr]
        except Exception:
            pass

        return []

    # --------------------------------------------------
    # GT evaluation
    # --------------------------------------------------
    def flatten_predictions(self, preds):
        """Recursively flattens deeply nested lists generated by models."""
        flat = []
        for item in preds:
            if isinstance(item, list):
                flat.extend(self.flatten_predictions(item))
            else:
                flat.append(item)
        return flat

    def evaluate_against_gt(self, model_raw_text, gt_value):
        """
        Analyzes the GT to determine structure, then applies the
        corresponding extraction/matching logic to the model text.
        """
        gt_clean = str(gt_value).replace('"', '').replace("'", "")

        # 1. IDENTIFY GT STRUCTURE USING THE CLEANED STRING
        is_list = "," in gt_clean or bool(re.search(r'\d+\.', gt_clean))
        is_numeric = bool(re.search(r'^\d+(\.\d+)?$', gt_clean.strip()))
        # 2. MATCHING LOGIC

        # CASE A: Numeric Match
        if is_numeric:
            gt_num = float(re.search(r'\d+(\.\d+)?', str(gt_value)).group())
            model_nums = [float(n) for n in re.findall(r'-?\d+\.?\d*', str(model_raw_text))]
            return any(abs(gt_num - m) < 1e-6 for m in model_nums)

        # CASE B: List Match (The "Bag of Items" check)
        elif is_list:

            # Normalize GT: Split by commas or numbers
            gt_items = [i.strip().lower() for i in re.split(r'\d+\.|\,', str(gt_value)) if i.strip()]

            # Check: Does the model text contain all of these items?
            # We use a fuzzy match for each item to be robust to "natural language" variations
            if model_raw_text:

                model_text_lower = model_raw_text.lower()

                return all(any(fuzz.partial_ratio(gt_item, model_text_lower) > 85 for item_text in [model_text_lower])
                           for gt_item in gt_items)

            else:
                return False

        # CASE C: Entity/String Match
        else:
            if model_raw_text:
                return fuzz.partial_ratio(str(gt_value).lower(), model_raw_text.lower()) > 90
            else:
                return False
    # --------------------------------------------------
    # Sample evaluation
    # --------------------------------------------------

    def evaluate_model(self, sample):
        claim_hit = 0
        evidence_hit = 0
        both_hit = 0


        gold_claim = sample["gt_answers"]["Claim"]
        gold_evidence = sample["gt_answers"]["Evidence"]

        raw = sample["responses"][0]["raw_response"]
        preds = self.flatten_predictions(self.extract_answers(raw))


        has_claim = self.evaluate_against_gt(str(preds), gold_claim)
        has_evidence = self.evaluate_against_gt(str(preds), gold_evidence)

        # has_claim = self.evaluate_against_gt(raw, gold_claim)
        # has_evidence = self. evaluate_against_gt(raw, gold_evidence)

        # if not (has_claim and has_evidence) and len(preds) == 2:
        #     print(f"Claim: {gold_claim}")
        #     print(f"Evidence: {gold_evidence}")
        #     print(f"Model: {preds}")
        #     print()

        if has_claim:
            claim_hit += 1
        if has_evidence:
            evidence_hit += 1
        if has_claim and has_evidence:
            both_hit += 1

        sample["got_claim"] = claim_hit
        sample["got_evidence"] = evidence_hit
        sample["verdict"] = both_hit

        return sample

    # --------------------------------------------------
    # Dataset evaluation
    # --------------------------------------------------

    def evaluate_dataset(self, responses_dict):
        """
        Evaluate full dataset and augment all samples.
        """

        updated = deepcopy(responses_dict)

        total = 0
        claim_hit = 0
        evidence_hit = 0
        both_hit = 0

        for sid, sample in updated.items():

            total += 1

            updated_sample = self.evaluate_model(sample)

            if updated_sample["got_claim"]:
                claim_hit += 1

            if updated_sample["got_evidence"]:
                evidence_hit += 1

            if updated_sample["verdict"]:
                both_hit += 1

        metrics = {
            "total": total,
            "claim_recall": round(claim_hit / total, 4) if total else 0,
            "evidence_recall": round(evidence_hit / total, 4) if total else 0,
            "joint_recall": round(both_hit / total, 4) if total else 0,
        }

        return updated, metrics

# --------------------------------------------------
# Batch runner
# --------------------------------------------------


def run_recall_analysis(model_configs):
    """
    Evaluates extraction results for provided models and displays a formatted table.

    Args:
        model_configs (dict): Mapping of {DisplayName: RelativeFilePath}
    """
    evaluator = ExhaustiveRecallEvaluator()
    results = {}

    print("Evaluating recall metrics...")
    for model_name, file_path in model_configs.items():
        # Load data
        full_path = os.path.join(REPO_PATH, file_path)
        data = load_json(full_path)

        # Evaluate
        _, metrics = evaluator.evaluate_dataset(data)
        results[model_name] = metrics
        print(f"  - Evaluated: {model_name}")

    # Build DataFrame
    rows = []
    for model, m in results.items():
        rows.append({
            "Model": model,
            "Total": m["total"],
            "Claim Recall": m["claim_recall"] * 100,
            "Evidence Recall": m["evidence_recall"] * 100,
            "Joint Recall": m["joint_recall"] * 100
        })

    df = pd.DataFrame(rows)

    # Format and Style
    styled = df.style.format({
        "Claim Recall": "{:.1f}",
        "Evidence Recall": "{:.1f}",
        "Joint Recall": "{:.1f}"
    }).background_gradient(subset=["Joint Recall"], cmap="Greens")

    print("\n--- Recall Analysis Report ---")
    display(styled)
    return df